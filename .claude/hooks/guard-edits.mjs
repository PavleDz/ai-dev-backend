// PreToolUse hook (matcher: Edit|Write|MultiEdit): protects files that must not be edited by hand.
// Exit 0 lets the edit happen. Exit 2 blocks it and sends the stderr message back to the agent.
// Any parse or runtime failure exits 0, so a broken hook can never wedge the agent.
//
// 1. A committed Alembic migration is history: it has already run on someone else's database
//    (a teammate's laptop, CI, a server). Editing it makes databases drift apart. A new revision is the fix.
//    A freshly generated, still uncommitted revision stays editable, so autogenerate's output can be fixed.
// 2. `.env` holds secrets and is never written by the agent; `.env.example` holds the placeholders.
// 3. The lockfile is generated by `poetry`, never typed in.
import { execFileSync } from 'node:child_process'
import path from 'node:path'

const root = process.env.CLAUDE_PROJECT_DIR ?? path.resolve(import.meta.dirname, '../..')

const block = (why) => {
  process.stderr.write(`BLOCKED by guard-edits: ${why}\n`)
  process.exit(2)
}

const isCommitted = (file) => {
  try {
    const out = execFileSync('git', ['log', '-1', '--format=%H', '--', file], {
      cwd: path.dirname(file),
      stdio: ['ignore', 'pipe', 'ignore'],
      timeout: 10_000,
    })
    return out.toString().trim().length > 0
  } catch {
    return false // not a git repo, or git missing: nothing to protect
  }
}

let input = ''
process.stdin.on('data', (chunk) => (input += chunk))
process.stdin.on('end', () => {
  try {
    const raw = JSON.parse(input).tool_input?.file_path
    if (!raw) process.exit(0)
    const file = path.resolve(root, raw)
    const posix = file.split(path.sep).join('/')
    const name = path.basename(file)

    if (/^\.env(?:\..+)?$/.test(name) && name !== '.env.example') {
      block(`${name} holds secrets: edit .env.example with a placeholder and tell the user which value to set (rules/safety.md)`)
    }
    if (name === 'poetry.lock') {
      block(`${name} is generated: use \`poetry add\` (after the user approves the dependency), never edit a lockfile (ADR-013)`)
    }
    if (/\/alembic\/versions\/[^/]+\.py$/.test(posix) && isCommitted(file)) {
      block(`${path.relative(root, file)} is a committed migration and migrations are history: generate a new revision with \`poetry run makemigrations "<what changed>"\` and edit that one (ADR-004)`)
    }
    process.exit(0)
  } catch {
    process.exit(0)
  }
})
